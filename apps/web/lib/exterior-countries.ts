const norm = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");

const MAP = new Map<string, string>();
for (const [country, cities] of LIST) for (const c of cities) if (!MAP.has(norm(c))) MAP.set(norm(c), country);

/** País da cidade do exterior; "Outros" quando a cidade não está na tabela. */
export function countryOf(city: string): string {
  return MAP.get(norm(city)) ?? "Outros";
}
